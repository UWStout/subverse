console.log('')
console.log(`Seeded ${1 + teachers.length + students.length} users (1 admin, ${teachers.length} teachers, ${students.length} students),`)
console.log(`${CLASSES.length} classes, ${offerings.length} offerings, ${projects.length} projects, ${assignments.length} assignments.`)
console.log(`All accounts use the password: ${TEST_PASSWORD}`)
console.log('')
console.log('Example logins:')
console.log(`  admin:    ${result.adminRow.username}`)
result.teacherRows.forEach((t, i) => {
  const off = offerings[i]
  const cls = CLASSES[off.classIndex]
  console.log(`  teacher:  ${t.username}  (teaches ${cls.subject} ${cls.number} - ${off.term}, section ${off.section})`)
})
for (const s of result.studentRows.slice(0, 5)) {
  const n = assignments.filter(a => result.studentRows[a.studentIndex].id === s.id).length
  console.log(`  student:  ${s.username}  (${n} project assignment${n === 1 ? '' : 's'})`)
}
if (result.studentRows.length > 5) {
  console.log(`  ... and ${result.studentRows.length - 5} more students`)
}

process.exit(0)
